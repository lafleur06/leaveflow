-- Phase 1: core organisation structure.

create table departments (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    description varchar(255),
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null
);

-- Case-insensitive uniqueness: "Finance" and "finance" are the same department.
create unique index uk_departments_name on departments (lower(name));

create table employees (
    id            bigint generated by default as identity primary key,
    first_name    varchar(50)  not null,
    last_name     varchar(50)  not null,
    email         varchar(150) not null,
    job_title     varchar(100),
    hire_date     date         not null,
    birth_date    date         not null,
    department_id bigint       not null references departments (id),
    manager_id    bigint       references employees (id),
    active        boolean      not null default true,
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null,
    constraint ck_employees_manager_not_self check (manager_id <> id),
    constraint ck_employees_hired_after_birth check (hire_date > birth_date)
);

create unique index uk_employees_email on employees (lower(email));
create index ix_employees_department_id on employees (department_id);
create index ix_employees_manager_id on employees (manager_id);
