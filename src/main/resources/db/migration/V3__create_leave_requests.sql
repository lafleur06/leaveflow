-- Phase 2: leave requests and their approval workflow.

create table leave_requests (
    id             bigint generated by default as identity primary key,
    employee_id    bigint       not null references employees (id),
    type           varchar(20)  not null,
    start_date     date         not null,
    end_date       date         not null,
    -- fixed when the request is created, so later holiday changes do not alter history
    working_days   integer      not null,
    reason         varchar(500),
    status         varchar(20)  not null,
    decided_by_id  bigint       references employees (id),
    decided_at     timestamptz,
    decision_note  varchar(500),
    -- optimistic locking: two managers deciding at the same moment cannot both win
    version        bigint       not null default 0,
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null,
    constraint ck_leave_requests_type check (type in ('ANNUAL', 'SICK', 'UNPAID')),
    constraint ck_leave_requests_status check (status in ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    constraint ck_leave_requests_dates check (end_date >= start_date),
    constraint ck_leave_requests_working_days check (working_days > 0)
);

create index ix_leave_requests_employee_dates on leave_requests (employee_id, start_date, end_date);
create index ix_leave_requests_status on leave_requests (status);
