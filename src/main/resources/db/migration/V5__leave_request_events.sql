-- Phase 5: audit trail. One row per status change of a leave request, never updated or deleted.

create table leave_request_events (
    id                bigint generated by default as identity primary key,
    leave_request_id  bigint       not null references leave_requests (id),
    action            varchar(20)  not null,
    -- who did it; empty only for cancellations recorded before this table existed
    actor_id          bigint       references employees (id),
    note              varchar(500),
    occurred_at       timestamptz  not null,
    constraint ck_leave_request_events_action check (action in ('SUBMITTED', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

create index ix_leave_request_events_request on leave_request_events (leave_request_id, occurred_at);

-- Rebuild the history of existing requests from what leave_requests already records.
insert into leave_request_events (leave_request_id, action, actor_id, note, occurred_at)
select id, 'SUBMITTED', employee_id, null, created_at
from leave_requests;

insert into leave_request_events (leave_request_id, action, actor_id, note, occurred_at)
select id, case when status = 'REJECTED' then 'REJECTED' else 'APPROVED' end, decided_by_id, decision_note, decided_at
from leave_requests
where decided_at is not null;

-- Who cancelled was not stored before, so the actor stays empty.
insert into leave_request_events (leave_request_id, action, actor_id, note, occurred_at)
select id, 'CANCELLED', null, null, updated_at
from leave_requests
where status = 'CANCELLED';
